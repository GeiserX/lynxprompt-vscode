/**
 * Regenerates src/utils/platformTable.ts from LynxPrompt's shared platform
 * table, so a pulled blueprint lands in the file the CLI and the web download
 * give its type.
 *
 *   bun scripts/sync-platform-table.ts <path to a LynxPrompt checkout> [commit]
 */
import { writeFileSync } from "fs";
import path from "path";

const [root, commit = "unknown"] = process.argv.slice(2);
if (!root) {
  console.error("usage: bun scripts/sync-platform-table.ts <LynxPrompt checkout> [commit]");
  process.exit(1);
}
const s = await import(path.resolve(root, "packages/shared/src/platforms.ts"));

const ruleFiles: Record<string, string> = {};
const commandFiles: Record<string, { directory: string; extension: string }> = {};
const types = [
  ...s.PLATFORMS.map((p: { blueprintType?: string }) => p.blueprintType).filter(Boolean),
  ...Object.keys(s.BLUEPRINT_TYPE_ALIASES),
];
for (const type of types) {
  if (type in ruleFiles || type in commandFiles) continue;
  const id = s.platformForBlueprintType(type);
  const platform = s.PLATFORMS.find((p: { id: string }) => p.id === id);
  const command = s.COMMANDS.find((c: { id: string }) => c.id === id);
  if (command) commandFiles[type] = { directory: command.directory, extension: command.extension };
  else if (platform) ruleFiles[type] = platform.file;
}
const full = (targets: { format: string; directory: string; extension: string }[]) =>
  targets.find((t) => t.format === "full")!;

const out = `// Generated by scripts/sync-platform-table.ts from LynxPrompt
// packages/shared/src/platforms.ts at ${commit}. Do not edit by hand.

/** Rules file each blueprint type is written to. */
export const RULE_FILES: Record<string, string> = ${JSON.stringify(ruleFiles, null, 2)};

/** Folder and extension of the command types, one file per command. */
export const COMMAND_FILES: Record<string, { directory: string; extension: string }> = ${JSON.stringify(commandFiles, null, 2)};

export const MCP_BLUEPRINT_TYPE = ${JSON.stringify(s.MCP_BLUEPRINT_TYPE)};
export const MCP_FILE = ${JSON.stringify(s.MCP_CONFIGS[0].file)};

export const SKILL_BLUEPRINT_TYPE = ${JSON.stringify(s.SKILL_BLUEPRINT_TYPE)};
export const SKILL_DIRECTORY = ${JSON.stringify(full(s.SKILL_TARGETS).directory)};

export const SUBAGENT_BLUEPRINT_TYPE = ${JSON.stringify(s.SUBAGENT_BLUEPRINT_TYPE)};
export const SUBAGENT_DIRECTORY = ${JSON.stringify(full(s.SUBAGENT_TARGETS).directory)};
export const SUBAGENT_EXTENSION = ${JSON.stringify(full(s.SUBAGENT_TARGETS).extension)};
`;
writeFileSync(path.join(import.meta.dir, "../src/utils/platformTable.ts"), out);
